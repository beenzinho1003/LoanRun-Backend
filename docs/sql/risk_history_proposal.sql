CREATE TABLE finance_change_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    data_revision BIGINT NOT NULL CHECK (data_revision > 0),
    origin VARCHAR(24) NOT NULL CHECK (origin IN ('PROFILE','MONTHLY_BUDGET','INCOME_ENTRY')),
    basis_month DATE NOT NULL CHECK (EXTRACT(DAY FROM basis_month)=1),
    event_date DATE NOT NULL,
    kind VARCHAR(8) NOT NULL CHECK (kind IN ('INCOME','EXPENSE')),
    before_amount BIGINT CHECK (before_amount >= 0),
    after_amount BIGINT CHECK (after_amount >= 0),
    cash_impact_known BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (before_amount IS DISTINCT FROM after_amount),
    CHECK (NOT cash_impact_known OR (before_amount IS NOT NULL AND after_amount IS NOT NULL)),
    UNIQUE(user_id,data_revision,origin,kind)
);
CREATE INDEX finance_change_events_owner_date ON finance_change_events(user_id,event_date,id);

CREATE TABLE risk_assessment_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    basis_month DATE NOT NULL CHECK (EXTRACT(DAY FROM basis_month)=1),
    data_revision BIGINT NOT NULL CHECK (data_revision >= 0),
    as_of DATE NOT NULL,
    input_hash VARCHAR(64) NOT NULL CHECK (input_hash ~ '^[a-f0-9]{64}$'),
    household_payload JSONB NOT NULL CHECK (jsonb_typeof(household_payload)='object'),
    loan_payloads JSONB NOT NULL CHECK (jsonb_typeof(loan_payloads)='object'),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (as_of=(basis_month+INTERVAL '1 month - 1 day')::DATE),
    UNIQUE(user_id,basis_month,data_revision)
);

-- Mutable derived-work marker. Old immutable results stay stored but cannot be served while dirty.
CREATE TABLE risk_assessment_requests (
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    basis_month DATE NOT NULL CHECK (EXTRACT(DAY FROM basis_month)=1),
    data_revision BIGINT NOT NULL CHECK (data_revision >= 0),
    pending BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY(user_id,basis_month)
);

CREATE FUNCTION reject_risk_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Risk history is append-only';
END;
$$;
CREATE TRIGGER finance_change_events_immutable BEFORE UPDATE OR DELETE ON finance_change_events
    FOR EACH ROW EXECUTE FUNCTION reject_risk_history_mutation();
CREATE TRIGGER risk_assessment_versions_immutable BEFORE UPDATE OR DELETE ON risk_assessment_versions
    FOR EACH ROW EXECUTE FUNCTION reject_risk_history_mutation();
