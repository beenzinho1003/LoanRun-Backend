CREATE TABLE finance_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES demo_users(id),
    monthly_income BIGINT NOT NULL CHECK (monthly_income >= 0),
    income_type VARCHAR(16) NOT NULL CHECK (income_type IN ('REGULAR','IRREGULAR')),
    payday INTEGER,
    fixed_essential_expenses BIGINT NOT NULL CHECK (fixed_essential_expenses >= 0),
    variable_essential_expenses BIGINT NOT NULL CHECK (variable_essential_expenses >= 0),
    discretionary_expenses BIGINT NOT NULL CHECK (discretionary_expenses >= 0),
    savings BIGINT NOT NULL CHECK (savings >= 0),
    emergency_fund BIGINT CHECK (emergency_fund >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK ((income_type='REGULAR' AND payday IS NOT NULL AND payday BETWEEN 1 AND 31) OR (income_type='IRREGULAR' AND payday IS NULL))
);

CREATE TABLE monthly_budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    year_month DATE NOT NULL CHECK (EXTRACT(DAY FROM year_month)=1),
    income_type VARCHAR(16) NOT NULL CHECK (income_type IN ('REGULAR','IRREGULAR')),
    expected_income BIGINT NOT NULL CHECK (expected_income >= 0),
    payday INTEGER,
    fixed_essential_expenses BIGINT NOT NULL CHECK (fixed_essential_expenses >= 0),
    variable_essential_expenses BIGINT NOT NULL CHECK (variable_essential_expenses >= 0),
    discretionary_expenses BIGINT NOT NULL CHECK (discretionary_expenses >= 0),
    discretionary_limit BIGINT NOT NULL CHECK (discretionary_limit >= 0),
    savings BIGINT NOT NULL CHECK (savings >= 0),
    emergency_fund BIGINT CHECK (emergency_fund >= 0),
    source VARCHAR(8) NOT NULL DEFAULT 'DEFAULT' CHECK (source IN ('DEFAULT','INPUT')),
    expenses_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    income_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    allocation_overridden BOOLEAN NOT NULL DEFAULT FALSE,
    reserve_amount BIGINT NOT NULL DEFAULT 0 CHECK (reserve_amount >= 0),
    carry_in BIGINT NOT NULL DEFAULT 0 CHECK (carry_in >= 0),
    carry_out BIGINT CHECK (carry_out >= 0),
    reserve_settled BIGINT CHECK (reserve_settled >= 0),
    settlement_status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (settlement_status IN ('OPEN','SETTLED','INSUFFICIENT')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(user_id,year_month)
);

CREATE TABLE income_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    budget_id BIGINT NOT NULL REFERENCES monthly_budgets(id),
    entry_type VARCHAR(16) NOT NULL CHECK (entry_type IN ('EXTRA','IRREGULAR')),
    received_date DATE NOT NULL,
    amount BIGINT NOT NULL CHECK (amount > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX income_entries_user_date_idx ON income_entries(user_id, received_date);

CREATE TABLE monthly_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_id BIGINT NOT NULL REFERENCES monthly_budgets(id),
    loan_id BIGINT NOT NULL,
    allocation_type VARCHAR(24) NOT NULL CHECK (allocation_type IN ('EXTRA_PAYMENT','REPAYMENT_SAVING')),
    amount BIGINT NOT NULL CHECK (amount >= 0),
    UNIQUE(budget_id,loan_id)
);

CREATE TABLE financial_institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL
);
CREATE TABLE loan_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES financial_institutions(id),
    external_code VARCHAR(100) NOT NULL,
    name VARCHAR(300) NOT NULL,
    loan_type VARCHAR(16) NOT NULL CHECK (loan_type IN ('CREDIT','MORTGAGE','JEONSE','STUDENT','AUTO','OTHER')),
    repayment_methods TEXT NOT NULL DEFAULT '',
    source VARCHAR(16) NOT NULL CHECK (source IN ('LIVE','CACHE','SEED')),
    source_url TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    eligible BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE(institution_id,external_code,loan_type)
);
