-- Team 1 source loan/ledger baseline. Product IDs stay scalar until the Team 2 catalog FK is coordinated.
CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    product_id BIGINT CHECK (product_id > 0),
    institution_name TEXT NOT NULL CHECK (length(trim(institution_name)) > 0),
    product_name TEXT NOT NULL CHECK (length(trim(product_name)) > 0),
    loan_form TEXT NOT NULL CHECK (loan_form='GENERAL'),
    loan_type TEXT NOT NULL CHECK (loan_type IN ('CREDIT','MORTGAGE','JEONSE','STUDENT','AUTO','OTHER')),
    repayment_method TEXT NOT NULL CHECK (repayment_method IN ('EQUAL_PAYMENT','EQUAL_PRINCIPAL','GRACE_INSTALLMENT','BULLET')),
    original_principal BIGINT NOT NULL CHECK (original_principal > 0),
    remaining_principal BIGINT NOT NULL CHECK (remaining_principal BETWEEN 0 AND original_principal),
    annual_rate NUMERIC NOT NULL CHECK (annual_rate >= 0 AND annual_rate < 30),
    rate_type TEXT NOT NULL CHECK (rate_type IN ('FIXED','VARIABLE')),
    rate_reset_months INTEGER CHECK (rate_reset_months IN (3,6,12)),
    next_rate_reset_date DATE,
    start_date DATE NOT NULL,
    maturity_date DATE NOT NULL CHECK (maturity_date > start_date),
    payment_day INTEGER NOT NULL CHECK (payment_day BETWEEN 1 AND 31),
    next_due_date DATE NOT NULL,
    contractual_monthly_payment BIGINT CHECK (contractual_monthly_payment >= 0),
    base_anchor_amount BIGINT CHECK (base_anchor_amount >= 0),
    fixed_principal BIGINT CHECK (fixed_principal >= 0),
    grace_months INTEGER NOT NULL CHECK (grace_months >= 0),
    grace_end_date DATE,
    post_grace_method TEXT CHECK (post_grace_method IN ('EQUAL_PAYMENT','EQUAL_PRINCIPAL')),
    prepayment_policy TEXT CHECK (prepayment_policy IN ('KEEP_PAYMENT','KEEP_MATURITY')),
    prepayment_fee_method TEXT NOT NULL CHECK (prepayment_fee_method IN ('FIXED','LINEAR','NONE','UNKNOWN')),
    prepayment_fee_rate NUMERIC CHECK (prepayment_fee_rate >= 0),
    fee_start_date DATE,
    fee_end_date DATE,
    fee_exempt BOOLEAN,
    initial_savings_balance BIGINT NOT NULL CHECK (initial_savings_balance >= 0),
    status TEXT NOT NULL CHECK (status IN ('ACTIVE','PAID','DELETED')),
    snapshot_date DATE NOT NULL,
    snapshot_principal BIGINT NOT NULL CHECK (snapshot_principal >= 0),
    -- Immutable registration-time default, not the later V4 versioned plan history.
    initial_plan_snapshot JSONB NOT NULL CHECK (jsonb_typeof(initial_plan_snapshot)='object'),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(user_id,id),
    CHECK (rate_type='VARIABLE' OR (rate_reset_months IS NULL AND next_rate_reset_date IS NULL)),
    CHECK ((repayment_method='BULLET' AND prepayment_policy IS NULL) OR
           (repayment_method<>'BULLET' AND prepayment_policy IS NOT NULL)),
    CHECK (repayment_method='BULLET' OR initial_savings_balance=0),
    CHECK ((repayment_method='GRACE_INSTALLMENT' AND grace_months>0 AND grace_end_date IS NOT NULL AND post_grace_method IS NOT NULL AND grace_end_date<maturity_date)
        OR (repayment_method<>'GRACE_INSTALLMENT' AND grace_months=0 AND grace_end_date IS NULL AND post_grace_method IS NULL)),
    CHECK (fee_end_date IS NULL OR fee_start_date IS NULL OR fee_end_date>=fee_start_date),
    CHECK (prepayment_fee_method NOT IN ('FIXED','LINEAR') OR prepayment_fee_rate IS NOT NULL),
    CHECK (prepayment_fee_method<>'LINEAR' OR (fee_start_date IS NOT NULL AND fee_end_date IS NOT NULL AND fee_end_date>fee_start_date))
);
CREATE INDEX loans_user_status_idx ON loans(user_id,status);

CREATE TABLE loan_balance_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    effective_date DATE NOT NULL,
    amount BIGINT NOT NULL CHECK (amount>=0),
    reason TEXT NOT NULL CHECK (reason IN ('REGISTRATION','CORRECTION')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id)
);
CREATE INDEX loan_balance_snapshot_order_idx ON loan_balance_snapshots(loan_id,effective_date,id);
CREATE TABLE loan_rate_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    annual_rate NUMERIC NOT NULL CHECK (annual_rate>=0 AND annual_rate<30),
    effective_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id)
);
CREATE INDEX loan_rate_history_order_idx ON loan_rate_histories(loan_id,effective_date,id);
CREATE TABLE due_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    due_date DATE NOT NULL,
    principal_amount BIGINT NOT NULL CHECK (principal_amount>=0),
    interest_amount BIGINT NOT NULL CHECK (interest_amount>=0),
    fee_amount BIGINT NOT NULL DEFAULT 0 CHECK (fee_amount>=0),
    contractual_amount BIGINT CHECK (contractual_amount>=0),
    required_amount BIGINT NOT NULL CHECK (required_amount>=0),
    confirmed_unpaid BOOLEAN NOT NULL DEFAULT FALSE,
    terms_revision BIGINT NOT NULL CHECK (terms_revision>=0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id),
    UNIQUE(user_id,loan_id,id),
    UNIQUE(loan_id,due_date),
    CHECK (required_amount=COALESCE(contractual_amount,principal_amount+interest_amount+fee_amount))
);
CREATE INDEX due_items_user_date_idx ON due_items(user_id,due_date);
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    paid_at DATE NOT NULL,
    payment_type TEXT NOT NULL CHECK (payment_type IN ('REGULAR','EXTRA')),
    amount BIGINT NOT NULL CHECK (amount>0),
    principal_amount BIGINT NOT NULL CHECK (principal_amount>=0),
    extra_amount BIGINT NOT NULL CHECK (extra_amount>=0),
    interest_amount BIGINT NOT NULL CHECK (interest_amount>=0),
    fee_amount BIGINT NOT NULL CHECK (fee_amount>=0),
    savings_used_amount BIGINT NOT NULL CHECK (savings_used_amount>=0 AND savings_used_amount<=principal_amount+extra_amount),
    memo TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id),
    UNIQUE(user_id,loan_id,id),
    CHECK (amount=principal_amount+extra_amount+interest_amount+fee_amount)
);
CREATE INDEX payments_user_date_idx ON payments(user_id,paid_at,id);
CREATE TABLE payment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    payment_id BIGINT NOT NULL,
    due_item_id BIGINT NOT NULL,
    principal_amount BIGINT NOT NULL CHECK (principal_amount>=0),
    interest_amount BIGINT NOT NULL CHECK (interest_amount>=0),
    fee_amount BIGINT NOT NULL CHECK (fee_amount>=0),
    FOREIGN KEY(user_id,loan_id,payment_id) REFERENCES payments(user_id,loan_id,id),
    FOREIGN KEY(user_id,loan_id,due_item_id) REFERENCES due_items(user_id,loan_id,id),
    UNIQUE(payment_id,due_item_id)
);
CREATE TABLE repayment_savings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    loan_id BIGINT NOT NULL,
    saved_at DATE NOT NULL,
    amount BIGINT NOT NULL CHECK (amount>0),
    memo TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY(user_id,loan_id) REFERENCES loans(user_id,id)
);
CREATE INDEX repayment_savings_user_date_idx ON repayment_savings(user_id,saved_at,id);
